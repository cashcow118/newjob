def main(uni_path, out_path):
    uni = list(csv.DictReader(open(uni_path, encoding="utf-8-sig")))
    codes = [r["Code"].strip() for r in uni]
    names = {r["Code"].strip(): r["Name"].strip() for r in uni}

    missing = [c for c in codes if c not in SECTOR]
    extra = [c for c in SECTOR if c not in codes]
    dup = [c for c, n in Counter(codes).items() if n > 1]

    print(f"유니버스 {len(codes)}종목 / 분류표 {len(SECTOR)}건")
    if missing:
        print("❌ 업종 누락:", [(c, names[c]) for c in missing])
    if extra:
        print("❌ 유니버스에 없는 코드:", extra)
    if dup:
        print("❌ 유니버스 중복 코드:", dup)
    if missing or extra or dup:
        sys.exit(1)
    print("✅ 100종목 전부 매핑, 누락·잉여·중복 없음")

    with open(out_path, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerow(["Code", "Name", "Sector"])
        for c in codes:
            w.writerow([c, names[c], SECTOR[c]])
    print(f"저장: {out_path}")

    cnt = Counter(SECTOR[c] for c in codes)
    print(f"\n업종 {len(cnt)}개:")
    for s, n in cnt.most_common():
        members = ", ".join(names[c] for c in codes if SECTOR[c] == s)
        flag = "  ← 2개 상한 작동" if n > 2 else ""
        print(f"  {s:<10} {n:2d}  {members}{flag}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
